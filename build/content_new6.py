"<p><strong>Short answer:</strong> blinds are treatments with hard slats you tilt. The families that "
"matter are real wood, faux wood, composite, aluminium and vertical, and the right one is usually "
"decided by the room rather than the look.</p>"
"<h2>What counts as a blind</h2>"
"<p>A blind has slats. You tilt them to aim the light and raise them to clear the glass. That is the "
"line between blinds and shades: a shade is a single piece of fabric that goes up and down, a blind "
